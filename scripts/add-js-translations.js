// Merge into each locale file
let updated = 0;
for (const lang of LANGS) {
  const filePath = path.join(LOCALES_DIR, `${lang}.json`);
  let existing = {};
  try { existing = JSON.parse(fs.readFileSync(filePath, 'utf8')); } catch {}

  const additions = MANUAL[lang] || {};
  let added = 0;
  for (const [sk, tr] of Object.entries(additions)) {
    if (!existing[sk]) {
      existing[sk] = tr;
      added++;
    }
  }

  if (added > 0) {
    fs.writeFileSync(filePath, JSON.stringify(existing, null, 2) + '\n', 'utf8');
    console.log(`${lang}: added ${added} keys`);
    updated++;
  } else {
    console.log(`${lang}: already up to date`);
  }
}
console.log(`\nDone — updated ${updated} files.`);
